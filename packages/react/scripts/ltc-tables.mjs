// Writes src/primitives/surface/ltc/ltc64Half.ts, the softbox key's LTC
// tables, from three's RectAreaLightTexturesLib.
//
// three ships the tables as 32,768 decimal literals. RectAreaLightNode reads
// all four channels of the first table and only x and y of the second
// (PhysicalLightingModel.directRectArea), so the module keeps six channels as
// half floats, stored as byte planes (low bytes, then high bytes) because gzip
// finds longer runs in the exponent bytes alone. docs/softbox-size.md records
// the sizes and the pixel comparison behind this form.
//
// Run from the repo root: node packages/react/scripts/ltc-tables.mjs

import { writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { DataUtils } from 'three'
import { RectAreaLightTexturesLib } from 'three/examples/jsm/lights/RectAreaLightTexturesLib.js'

const SIZE = 64
const TARGET = new URL('../src/primitives/surface/ltc/ltc64Half.ts', import.meta.url)

RectAreaLightTexturesLib.init()
const first = RectAreaLightTexturesLib.LTC_FLOAT_1.image.data
const second = RectAreaLightTexturesLib.LTC_FLOAT_2.image.data
const used = []
for (let texel = 0; texel < SIZE * SIZE; texel++) for (let c = 0; c < 4; c++) used.push(first[texel * 4 + c])
for (let texel = 0; texel < SIZE * SIZE; texel++) for (let c = 0; c < 2; c++) used.push(second[texel * 4 + c])

const halves = Uint16Array.from(used, (value) => DataUtils.toHalfFloat(value))
const planes = new Uint8Array(halves.length * 2)
for (let index = 0; index < halves.length; index++) {
  planes[index] = halves[index] & 255
  planes[halves.length + index] = halves[index] >> 8
}

let maxError = 0
for (let index = 0; index < used.length; index++) maxError = Math.max(maxError, Math.abs(used[index] - DataUtils.fromHalfFloat(halves[index])))

const base64 = Buffer.from(planes).toString('base64')
writeFileSync(TARGET, `// Generated by packages/react/scripts/ltc-tables.mjs. ${SIZE} × ${SIZE} texels, six half-float channels in byte planes.\nexport default '${base64}'\n`)
console.log(JSON.stringify({ values: used.length, maxError, gzip: gzipSync(base64, { level: 9 }).length }))
