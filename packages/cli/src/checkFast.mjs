// Fast static staleness verifier for compiled *.material.gen.ts manifests.
// Folds compiler authoring helper hashes into ABI so edits invalidate stale outputs.

import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import path from 'node:path'

const ABI_TAG = 'v2.1'
let cachedAbi = null

export function sha256Hex(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}

export function getCompilerAbi() {
  if (cachedAbi) return cachedAbi
  const authorSrc = readFileSync(path.join(import.meta.dirname, 'author.ts'), 'utf8')
  const ltcSrc = readFileSync(path.join(import.meta.dirname, 'ltcAuthor.ts'), 'utf8')
  cachedAbi = `${ABI_TAG}-${sha256Hex(`${ABI_TAG}\n${authorSrc}\n${ltcSrc}`).slice(0, 16)}`
  return cachedAbi
}

export function computeMaterialSourceHash(srcText, manifestImport) {
  return sha256Hex(`${getCompilerAbi()}\n${manifestImport}\n${srcText}`)
}

export function formatManifestFile(baseName, bodyCode) {
  const header1 = `// Generated by \`munari compile\` from ${baseName}. Zero TypeGPU runtime dependencies.`
  const bodyHash = sha256Hex(bodyCode)
  const header2 = `// munari-body-sha256: ${bodyHash}`
  return `${header1}\n${header2}\n${bodyCode}`
}

export function rewriteManifestImport(genText, srcText, nextImport) {
  const firstNl = genText.indexOf('\n')
  const secondNl = firstNl >= 0 ? genText.indexOf('\n', firstNl + 1) : -1
  if (secondNl < 0) return genText.replace("'@petepetrash/munari/gpu'", `'${nextImport}'`)
  const header1 = genText.slice(0, firstNl)
  let body = genText.slice(secondNl + 1).replace("'@petepetrash/munari/gpu'", `'${nextImport}'`)
  if (srcText) {
    const nextSrcHash = computeMaterialSourceHash(srcText, nextImport)
    body = body.replace(/\bsourceHash:\s*"[0-9a-f]{64}"/, `sourceHash: "${nextSrcHash}"`)
  }
  return `${header1}\n// munari-body-sha256: ${sha256Hex(body)}\n${body}`
}

export function checkMaterialFileFast(absPath, options = {}) {
  const rawImport = options?.manifestImport
  if (rawImport !== undefined && (rawImport === null || rawImport.constructor !== String || rawImport.trim() === '')) {
    throw new Error(`${absPath}: options.manifestImport must be a non-empty string`)
  }
  const manifestImport = rawImport ?? '@petepetrash/munari/gpu'
  const outPath = absPath.replace(/\.material\.ts$/, '.material.gen.ts')
  let genText = ''
  try {
    genText = readFileSync(outPath, 'utf8')
  } catch {
    return { name: path.basename(absPath, '.material.ts'), outPath, ok: false, reason: 'missing' }
  }

  const firstNl = genText.indexOf('\n')
  const secondNl = firstNl >= 0 ? genText.indexOf('\n', firstNl + 1) : -1
  if (secondNl < 0) {
    return { name: path.basename(absPath, '.material.ts'), outPath, ok: false, reason: 'stale' }
  }
  const hashLine = genText.slice(firstNl + 1, secondNl)
  const bodyMatch = /^\/\/ munari-body-sha256: ([0-9a-f]{64})$/.exec(hashLine)
  if (!bodyMatch) {
    return { name: path.basename(absPath, '.material.ts'), outPath, ok: false, reason: 'stale' }
  }
  const actualBodyHash = sha256Hex(genText.slice(secondNl + 1))
  if (actualBodyHash !== bodyMatch[1]) {
    return { name: path.basename(absPath, '.material.ts'), outPath, ok: false, reason: 'stale' }
  }

  const nameMatch = /\bname:\s*"([^"]+)"/.exec(genText)
  const srcMatch = /\bsourceHash:\s*"([0-9a-f]{64})"/.exec(genText)
  const expectedSrcHash = computeMaterialSourceHash(readFileSync(absPath, 'utf8'), manifestImport)
  const ok = Boolean(srcMatch && srcMatch[1] === expectedSrcHash)
  return {
    name: nameMatch ? nameMatch[1] : path.basename(absPath, '.material.ts'),
    outPath,
    ok,
    reason: ok ? 'up-to-date' : 'stale',
  }
}
